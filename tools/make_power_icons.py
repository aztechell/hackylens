from pathlib import Path
import math

def triangle(x,y,a,b,c):
 def edge(p,q): return (x-q[0])*(p[1]-q[1])-(p[0]-q[0])*(y-q[1])
 es=[edge(a,b),edge(b,c),edge(c,a)]
 return min(es)>=0 or max(es)<=0
masks=[]
for icon in range(3):
 data=[]
 for y in range(48):
  row=[]
  for x in range(48):
   dx=x-23.5;dy=y-23.5;r=dx*dx+dy*dy
   if icon==0: bit=r<=20.5**2 and ((x-31.0)**2+(y-17.5)**2>19.0**2)
   elif icon==1: bit=(16.0**2<=r<=20.5**2 and not (abs(dx)<9 and dy<-8)) or (21<=x<=26 and 2<=y<=24)
   else: bit=(16.0**2<=r<=20.5**2 and not (x>=27 and y<16)) or triangle(x,y,(39,8),(28,0),(25,13))
   row.append(bit)
  for offset in range(0,48,8): data.append(sum(int(row[offset+k])<<(7-k) for k in range(8)))
 masks.append(data)
lines=['/* Shared 48px monochrome power glyphs. Generated by tools/make_power_icons.py. */','#ifndef HK_POWER_ICONS_1BPP_H','#define HK_POWER_ICONS_1BPP_H','#include <stdint.h>','#define HK_POWER_ICON_SIZE 48U','enum { HK_POWER_ICON_SLEEP, HK_POWER_ICON_OFF, HK_POWER_ICON_RESTART };','static const uint8_t hk_power_icons_1bpp[3][288] = {']
for data in masks:
 lines.append('    {')
 for i in range(0,len(data),12): lines.append('        '+', '.join(f'0x{v:02x}' for v in data[i:i+12])+',')
 lines.append('    },')
lines+=['};','static inline uint8_t hk_power_icon_pixel(unsigned icon, unsigned x, unsigned y)','{','    return (uint8_t)((hk_power_icons_1bpp[icon][y*6U+x/8U] >> (7U-(x&7U))) & 1U);','}','#endif','']
Path('firmware/assets/hackylens_power_icons_1bpp.h').write_text('\n'.join(lines))
